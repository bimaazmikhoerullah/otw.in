package com.example.otwin.database

import android.content.Context
import android.content.Intent
import android.util.Log
import com.example.otwin.R
import com.google.android.gms.auth.api.signin.GoogleSignIn
import com.google.android.gms.auth.api.signin.GoogleSignInAccount
import com.google.android.gms.auth.api.signin.GoogleSignInOptions
import com.google.android.gms.common.ConnectionResult
import com.google.android.gms.common.GoogleApiAvailability
import com.google.android.gms.common.api.ApiException
import com.google.android.gms.common.api.CommonStatusCodes
import com.google.firebase.auth.FirebaseAuthException
import com.google.firebase.auth.GoogleAuthProvider

/** Google (Gmail) Sign-In through Firebase Authentication. */
class GoogleAuthRepository(private val context: Context) {

    /**
     * Prefer the Web client ID generated by the google-services plugin from
     * google-services.json (oauth_client with client_type 3). Fall back only if
     * the JSON has no OAuth client configured yet.
     */
    private val webClientId: String
        get() {
            val generatedId = context.resources.getIdentifier(
                "default_web_client_id",
                "string",
                context.packageName
            )
            val fromJson = if (generatedId == 0) {
                null
            } else {
                context.getString(generatedId).trim().takeIf { it.isNotBlank() }
            }
            return fromJson ?: context.getString(R.string.google_web_client_id_fallback).trim()
        }

    /**
     * Google Sign-In only needs google-services.json + the Web client ID.
     * The Realtime Database URL is optional here (profiles are saved only when set).
     */
    val isConfigured: Boolean
        get() = FirebaseService.isFirebaseReady &&
            webClientId.isNotBlank() &&
            !webClientId.startsWith("YOUR_", ignoreCase = true) &&
            webClientId.endsWith(".apps.googleusercontent.com", ignoreCase = true)

    private val signInOptions: GoogleSignInOptions
        get() = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
            .requestIdToken(webClientId)
            .requestEmail()
            .build()

    fun getSignInIntent(): Intent =
        GoogleSignIn.getClient(context, signInOptions).signInIntent

    fun handleResult(data: Intent?, onResult: (AuthResult) -> Unit) {
        if (!isConfigured) {
            onResult(AuthResult.Failure(R.string.auth_google_not_configured))
            return
        }

        val playServices =
            GoogleApiAvailability.getInstance().isGooglePlayServicesAvailable(context)
        if (playServices != ConnectionResult.SUCCESS) {
            val detail = GoogleApiAvailability.getInstance()
                .getErrorString(playServices)
            Log.e(TAG, "Google Play services unavailable: $playServices $detail")
            onResult(AuthResult.Failure(R.string.auth_google_play_services, detail))
            return
        }

        if (data == null) {
            onResult(AuthResult.Failure(R.string.auth_google_cancelled))
            return
        }

        try {
            val account: GoogleSignInAccount =
                GoogleSignIn.getSignedInAccountFromIntent(data)
                    .getResult(ApiException::class.java)

            val idToken = account.idToken
            if (idToken.isNullOrBlank()) {
                Log.e(TAG, "Google account returned no ID token. Check Web client ID.")
                onResult(AuthResult.Failure(R.string.auth_google_invalid_client))
                return
            }

            val credential = GoogleAuthProvider.getCredential(idToken, null)
            FirebaseService.auth.signInWithCredential(credential)
                .addOnSuccessListener { result ->
                    saveProfile(result.user?.uid, account, onResult)
                }
                .addOnFailureListener { error ->
                    Log.e(TAG, "Firebase credential exchange failed", error)
                    onResult(firebaseAuthFailure(error))
                }
        } catch (e: ApiException) {
            Log.e(TAG, "Google sign-in ApiException ${e.statusCode}: ${e.statusMessage}", e)
            if (e.statusCode == CommonStatusCodes.CANCELED) {
                onResult(AuthResult.Failure(R.string.auth_google_cancelled))
            } else {
                onResult(
                    AuthResult.Failure(
                        R.string.auth_google_error,
                        "${e.statusCode}: ${e.statusMessage}"
                    )
                )
            }
        } catch (e: Exception) {
            Log.e(TAG, "Google sign-in unexpected error", e)
            onResult(AuthResult.Failure(R.string.auth_google_error, e.message))
        }
    }

    private fun firebaseAuthFailure(error: Exception): AuthResult.Failure {
        if (error is FirebaseAuthException) {
            val code = error.errorCode
            val message = error.message
            Log.e(TAG, "FirebaseAuthException: $code - $message")
            return when (code) {
                "auth/account-exists-with-different-credential" ->
                    AuthResult.Failure(R.string.auth_google_account_exists, message)

                "auth/invalid-credential",
                "auth/invalid-id-token",
                "auth/id-token-expired",
                "auth/malformed-jwt" ->
                    AuthResult.Failure(R.string.auth_google_invalid_client, "$code: $message")

                else -> AuthResult.Failure(R.string.auth_google_error, "$code: $message")
            }
        }
        return AuthResult.Failure(R.string.auth_google_error, error.message)
    }

    private fun saveProfile(
        uid: String?,
        account: GoogleSignInAccount,
        onResult: (AuthResult) -> Unit
    ) {
        if (uid == null) {
            onResult(AuthResult.Failure(R.string.auth_google_error))
            return
        }

        // Profil sementara dipakai kalau database belum bisa dibaca/ditulis.
        val fallbackProfile = UserProfile(
            name = account.displayName.orEmpty(),
            email = account.email.orEmpty(),
            createdAt = System.currentTimeMillis()
        )

        // Login Google tetap jalan sebelum URL database diisi.
        if (!FirebaseService.isDatabaseConfigured) {
            onResult(AuthResult.Success(fallbackProfile))
            return
        }

        val ref = FirebaseService.usersReference().child(uid)
        ref.get()
            .addOnSuccessListener { snapshot ->
                val existing = snapshot.getValue(UserProfile::class.java)
                val profile = UserProfile(
                    name = account.displayName ?: existing?.name.orEmpty(),
                    username = existing?.username.orEmpty(),
                    email = account.email ?: existing?.email.orEmpty(),
                    phone = existing?.phone.orEmpty(),
                    createdAt = existing?.createdAt ?: System.currentTimeMillis()
                )

                ref.setValue(profile)
                    .addOnSuccessListener { onResult(AuthResult.Success(profile)) }
                    .addOnFailureListener { error ->
                        // Rules database mungkin belum di-publish. Jangan blokir login
                        // hanya karena profil gagal disimpan.
                        Log.e(TAG, "Failed to save Google profile; continuing sign-in", error)
                        onResult(AuthResult.Success(profile))
                    }
            }
            .addOnFailureListener { error ->
                Log.e(TAG, "Failed to read Google profile; continuing sign-in", error)
                onResult(AuthResult.Success(fallbackProfile))
            }
    }

    companion object {
        private const val TAG = "GoogleAuth"
    }
}
